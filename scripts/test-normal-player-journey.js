'use strict';
const assert=require('node:assert/strict');
const {initialize,entry}=require('./lib/journey-runtime');
const policy=require('./lib/journey-policy');
const {loadBson}=require('./verify-normal-progression');
const {ENHANCE_GEMS,getEnhanceCost}=require('../src/shared/enhanceConfig');
const {expToNextLevel}=require('../src/shared/progression');
async function main(){
 const snapshot=process.argv.find(a=>a.startsWith('--snapshot='))?.slice(11);assert.ok(snapshot);
 const matrix=policy.matrix(loadBson(snapshot+'/items.bson'),loadBson(snapshot+'/weeklyQuests.bson'));
 const route=matrix.included.find(x=>x.baseKey==='swordsman');
 const events=[],r=await initialize(snapshot,route,123,(type,data)=>events.push({type,...data}));
 const initial=r.progress.equipment.weapon.uuid;
 await policy.equipAndRecycle(r,'beginner');assert.equal(r.progress.equipment.weapon.uuid,initial,'no acquisition: no equipment');
 const bagItem=r.items.find(i=>i.itemType==='consumable'&&i.effect?.type==='grant_gold');assert.ok(bagItem);
 const bag=entry(bagItem,'monster_drop');r.progress.inventory.push(bag);const beforeBag=r.wallet.gold;
 await policy.equipAndRecycle(r,'beginner');assert.equal(r.wallet.gold,beforeBag+bag.itemEffect.value);assert.ok(!r.progress.inventory.some(i=>i.uuid===bag.uuid));
 const weapon=r.items.find(i=>i.tier==='C'&&i.weaponType==='sword_2h'&&i.itemType==='equipment');assert.ok(weapon);
 let gift=entry(weapon,'quest');r.progress.inventory.push(gift);
 await policy.equipAndRecycle(r,'mid');assert.equal(r.progress.equipment.weapon.uuid,gift.uuid,'actual quest gift may be equipped');
 gift=r.progress.equipment.weapon;
 assert.ok(!policy.isAcquired(entry(weapon,'invented')));
 const original=JSON.stringify(weapon);
 await assert.rejects(r.enhanceService.enhanceEquipment(r.id,gift.uuid),/寶石不足/);
 const gem=entry(r.items.find(i=>i.id===ENHANCE_GEMS.C));gem.stackCount=50;r.progress.inventory.push(gem);
 r.wallet.gold=0;await assert.rejects(r.enhanceService.enhanceEquipment(r.id,gift.uuid),/金幣不足/);
 r.wallet.gold=100000;const rng=Math.random;
 try{
  Math.random=()=>0;await r.enhanceService.enhanceEquipment(r.id,gift.uuid);
  const cost=getEnhanceCost('C',1);
  Math.random=()=>.99999;
  const beforeGold=r.wallet.gold,beforeGem=gem.stackCount,stats=JSON.stringify(gift.equipStats);
  const fail=await r.enhanceService.enhanceEquipment(r.id,gift.uuid);
  assert.equal(fail.success,false);assert.equal(gift.enhanceLevel,1);assert.equal(JSON.stringify(gift.equipStats),stats);
  assert.equal(r.wallet.gold,beforeGold-cost.goldRequired);assert.equal(gem.stackCount,beforeGem-cost.gemsRequired);
  Math.random=()=>0;const success=await r.enhanceService.enhanceEquipment(r.id,gift.uuid);
  assert.ok(success.success);assert.equal(gift.enhanceLevel,2);assert.notEqual(JSON.stringify(gift.equipStats),stats);
  assert.equal(JSON.stringify(weapon),original,'library prototype is unchanged');
  const spare=entry(weapon,'monster_drop');r.progress.inventory.push(spare);
  const gemsBefore=gem.stackCount;await r.shopService.discardItem(r.id,spare.uuid,{mode:'dismantle'});
  assert.equal(gem.stackCount,gemsBefore+1,'successful real dismantle awards its tier gem');
 }finally{Math.random=rng;}
 assert.equal(policy.cardScore({passiveEffects:[{key:'lifesteal',params:{value:99}}]},r.progress),0);
 assert.ok(policy.cardScore({monsterCardSkill:{key:'mistwood_beast_stomp'}},r.progress)>0);
 await r.progressService.grantExp({discordId:r.id,amount:expToNextLevel(1),source:'monster:kill'});
 assert.equal(r.progress.level,2);assert.equal(Object.values(r.progress.attributes).reduce((a,b)=>a+b,0),8);
 const badge=entry(r.items.find(i=>i.id===route.t1Badge));r.progress.equipment.job_eq=badge;
 r.wallet.gold=1000000;
 await assert.rejects(r.jobBadgeService.transferJob(r.id,route.t2Badge),/熟練度不足/);
 badge.jobExp=228;r.wallet.gold=0;
 await assert.rejects(r.jobBadgeService.transferJob(r.id,route.t2Badge),/金幣不足/);
 r.wallet.gold=1000000;
 const q=r.definitions.find(q=>q.id===route.t2Quest);
 await assert.rejects(r.claim(q),/尚未解鎖/);
 r.progress.level=35;
 const transferred=await r.claim(q);
 assert.equal(r.progress.equipment.job_eq.itemId,route.t2Badge);
 assert.equal(r.progress.equipment.job_eq.jobExp,0);assert.equal(r.wallet.gold,750000+(q.rewardGold||q.gold||0));
 assert.ok(transferred.jobTransfer);assert.ok(!Object.values(r.progress.equipment).some(i=>i?.itemId===route.t1Badge));
 assert.equal(r.forbidden.length,0);
 console.log('PASS: actual quest gear, no invented gear, real failure/success costs, dismantle gems, damage cards, two points per level, T2 gates/cost/fresh proficiency, immutable library');
}
main().catch(e=>{console.error(e.stack);process.exitCode=1});
