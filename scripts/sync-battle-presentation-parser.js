"use strict";
// Compile the existing Web replay parser for the server; no second combat formula.
const fs = require('fs');
const path = require('path');
const frontend = process.env.FRONTEND_ROOT || path.resolve(__dirname, '../../equipmentGAME-app');
const ts = require(path.join(frontend, 'node_modules/typescript'));
const source = fs.readFileSync(path.join(frontend, 'src/lib/battleStore.ts'), 'utf8');
const parser = source.slice(source.indexOf('const N ='), source.indexOf('\ninterface BattleStore {'));
if (!parser.includes('export function buildTimeline')) throw new Error('Replay parser boundaries changed');
const timing = fs.readFileSync(path.join(frontend, 'src/lib/battlePlaybackPresentation.ts'), 'utf8').replace(/^import[^\n]+\n/, '');
const output = ts.transpileModule(parser+'\n'+timing, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS } }).outputText;
fs.writeFileSync(path.resolve(__dirname, '../src/shared/battlePresentationParser.js'), '// Generated by scripts/sync-battle-presentation-parser.js from the current Web parser.\n'+output);
